"""Generate encoding-protocol charset tables and test fixtures from Python's codecs.

Run from the repository root:

    uv run --no-project tools/gen-charsets.py

Writes:
  src/single-byte-tables.lisp   core system: windows-125x, cp866, mac-roman, tis-620, cp874
  src/cjk/*-table.lisp          encoding-protocol/{iso-2022-jp,big5,euc-kr,gb18030}: JIS X 0208, big5, euc-kr, cp949, gb18030
  tests/fixtures/*.sexp         Python's answers, read by the Rove tests

Each table is the decode table plus the encoder's exceptions ("overrides") to
the inverse of that table. Before writing anything, the script runs a Python
model of the Lisp decoder/encoder against Python's codecs over every single
byte, every two-byte sequence and every code point, and stops on any mismatch.
"""

import codecs
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = (
    ";;;; Generated by tools/gen-charsets.py from Python {} codecs. Do not edit.\n"
    "\n(in-package #:encoding-protocol)\n"
).format(sys.version.split()[0])

ALL_CPS = [cp for cp in range(0x110000) if not 0xD800 <= cp <= 0xDFFF]
BMP_CPS = [cp for cp in ALL_CPS if cp < 0x10000]


def dec(data, codec):
    try:
        return data.decode(codec)
    except UnicodeDecodeError:
        return None


def enc(text, codec):
    try:
        return text.encode(codec)
    except UnicodeEncodeError:
        return None


def pack(octets):
    value = 0
    for b in octets:
        value = (value << 8) | b
    return value


def unpack(value):
    out = []
    while True:
        out.insert(0, value & 0xFF)
        value >>= 8
        if not value:
            return bytes(out)


def python_encode_map(codec, cps):
    table = {}
    for cp in cps:
        if cp < 0x80:
            continue
        out = enc(chr(cp), codec)
        if out is not None:
            table[cp] = out
    return table


def overrides(model_inverse, python_map):
    """Encoder exceptions: (cp . packed) where Python differs, (cp) where it cannot encode."""
    result = []
    for cp in sorted(set(model_inverse) | set(python_map)):
        want = python_map.get(cp)
        have = model_inverse.get(cp)
        if want != have:
            result.append((cp, pack(want) if want is not None else None))
    return result


def apply_overrides(inverse, overrides_list):
    inverse = dict(inverse)
    for cp, packed in overrides_list:
        if packed is None:
            inverse.pop(cp, None)
        else:
            inverse[cp] = unpack(packed)
    return inverse


def check(condition, message):
    if not condition:
        sys.exit("gen-charsets: " + message)


# ---------------------------------------------------------------- single byte

SINGLE_BYTE = [
    # (Lisp variable stem, Python codec)
    ("cp1250", "cp1250"), ("cp1253", "cp1253"), ("cp1254", "cp1254"),
    ("cp1255", "cp1255"), ("cp1256", "cp1256"), ("cp1257", "cp1257"),
    ("cp1258", "cp1258"), ("cp866", "cp866"), ("mac-roman", "mac_roman"),
    ("tis-620", "tis_620"), ("cp874", "cp874"),
]


def single_byte(codec):
    for b in range(0x80):
        check(dec(bytes([b]), codec) == chr(b), f"{codec}: byte {b:#x} is not ASCII")
    data = []
    for b in range(0x80, 0x100):
        text = dec(bytes([b]), codec)
        check(text is None or (len(text) == 1 and 0 < ord(text) < 0x10000),
              f"{codec}: byte {b:#x} -> {text!r}")
        data.append(ord(text) if text else 0)
    inverse = {}
    for i, cp in enumerate(data):
        if cp and cp not in inverse:
            inverse[cp] = bytes([0x80 + i])
    python_map = python_encode_map(codec, ALL_CPS)
    ovr = overrides(inverse, python_map)
    check(apply_overrides(inverse, ovr) == python_map, f"{codec}: encode model")
    return data, ovr, python_map


# ---------------------------------------------------------------- double byte


class Dbcs:
    """Two-byte table: lead/trail ranges, decode data, encode overrides."""

    def __init__(self, codec, decode_pair, lead_range=None):
        self.codec = codec
        pairs = {}
        for lead in range(0x80, 0x100) if lead_range is None else lead_range:
            for trail in range(0x100):
                text = decode_pair(bytes([lead, trail]))
                if text is not None and len(text) == 1:
                    pairs[(lead, trail)] = ord(text)
        check(pairs, f"{codec}: no pairs")
        check(all(0 < cp < 0x10000 for cp in pairs.values()), f"{codec}: non-BMP pair")
        self.lead_min = min(l for l, _ in pairs)
        self.lead_max = max(l for l, _ in pairs)
        self.trail_min = min(t for _, t in pairs)
        self.trail_max = max(t for _, t in pairs)
        span = self.trail_max - self.trail_min + 1
        self.data = [0] * ((self.lead_max - self.lead_min + 1) * span)
        for (lead, trail), cp in pairs.items():
            self.data[(lead - self.lead_min) * span + trail - self.trail_min] = cp
        self.inverse = {}
        for lead in range(self.lead_min, self.lead_max + 1):
            for trail in range(self.trail_min, self.trail_max + 1):
                cp = self.lookup(lead, trail)
                if cp and cp not in self.inverse:
                    self.inverse[cp] = bytes([lead, trail])

    def lookup(self, lead, trail):
        if not (self.lead_min <= lead <= self.lead_max
                and self.trail_min <= trail <= self.trail_max):
            return 0
        span = self.trail_max - self.trail_min + 1
        return self.data[(lead - self.lead_min) * span + trail - self.trail_min]


def dbcs_model_decode(table, data, extra=None):
    """The Lisp %DBCS-DECODE: returns a str, or None on any error."""
    out = []
    i = 0
    while i < len(data):
        b1 = data[i]
        if b1 < 0x80:
            out.append(chr(b1))
            i += 1
            continue
        if extra:
            handled = extra(data, i)
            if handled is not None:
                if handled is False:
                    return None
                cp, i = handled
                out.append(chr(cp))
                continue
        if not table.lead_min <= b1 <= table.lead_max or i + 1 >= len(data):
            return None
        cp = table.lookup(b1, data[i + 1])
        if not cp:
            return None
        out.append(chr(cp))
        i += 2
    return "".join(out)


def dbcs_model_encode_char(inverse, cp, extra=None):
    if cp < 0x80:
        return bytes([cp])
    if cp in inverse:
        return inverse[cp]
    if extra:
        return extra(cp)
    return None


def verify_dbcs(codec, table, inverse, extra_dec=None, extra_enc=None, cps=ALL_CPS):
    for b in range(0x100):
        check(dbcs_model_decode(table, bytes([b]), extra_dec) == dec(bytes([b]), codec),
              f"{codec}: single byte {b:#x}")
    for b1 in range(0x80, 0x100):
        for b2 in range(0x100):
            data = bytes([b1, b2])
            check(dbcs_model_decode(table, data, extra_dec) == dec(data, codec),
                  f"{codec}: pair {data.hex()}")
    for cp in cps:
        check(dbcs_model_encode_char(inverse, cp, extra_enc) == enc(chr(cp), codec),
              f"{codec}: encode U+{cp:04X}")


def plain_dbcs(codec):
    table = Dbcs(codec, lambda b: dec(b, codec))
    python_map = python_encode_map(codec, ALL_CPS)
    ovr = overrides(table.inverse, python_map)
    inverse = apply_overrides(table.inverse, ovr)
    verify_dbcs(codec, table, inverse)
    return table, ovr


# EUC-KR: KS X 1001 plus the KS X 1001:1998 Annex 3 eight-byte Hangul make-up
# sequence (A4 D4, then A4 + initial, A4 + medial, A4 + final).
def euc_kr():
    codec = "euc_kr"
    table = Dbcs(codec, lambda b: dec(b, codec))
    # A4 D4 is the filler: it only decodes as the start of a make-up sequence.
    check(table.lookup(0xA4, 0xD4) == 0, "euc_kr: A4D4 decodes alone")
    python_map = python_encode_map(codec, ALL_CPS)
    cho, jung, jong = [None] * 19, [None] * 21, [None] * 28
    makeup = {}
    for cp, out in python_map.items():
        if len(out) == 8:
            check(0xAC00 <= cp <= 0xD7A3 and out[:2] == b"\xa4\xd4"
                  and out[2] == out[4] == out[6] == 0xA4, f"euc_kr: make-up U+{cp:04X}")
            s = cp - 0xAC00
            for tab, idx, byte in ((cho, s // 588, out[3]), (jung, (s % 588) // 28, out[5]),
                                   (jong, s % 28, out[7])):
                check(tab[idx] in (None, byte), "euc_kr: jamo table")
                tab[idx] = byte
            makeup[cp] = out
    check(None not in cho + jung + jong, "euc_kr: incomplete jamo tables")

    def extra_dec(data, i):
        if data[i] != 0xA4 or i + 1 >= len(data) or data[i + 1] != 0xD4:
            return None
        if i + 8 > len(data) or not (data[i + 2] == data[i + 4] == data[i + 6] == 0xA4):
            return False
        try:
            l, v, t = cho.index(data[i + 3]), jung.index(data[i + 5]), jong.index(data[i + 7])
        except ValueError:
            return False
        return 0xAC00 + (l * 21 + v) * 28 + t, i + 8

    def extra_enc(cp):
        if 0xAC00 <= cp <= 0xD7A3:
            s = cp - 0xAC00
            return bytes([0xA4, 0xD4, 0xA4, cho[s // 588], 0xA4, jung[(s % 588) // 28],
                          0xA4, jong[s % 28]])
        return None

    plain = {cp: out for cp, out in python_map.items() if len(out) != 8}
    ovr = overrides(table.inverse, plain)
    inverse = apply_overrides(table.inverse, ovr)
    verify_dbcs(codec, table, inverse, extra_dec, extra_enc)
    # Every make-up sequence, valid and not.
    for l in range(19):
        for v in range(21):
            for t in range(28):
                data = bytes([0xA4, 0xD4, 0xA4, cho[l], 0xA4, jung[v], 0xA4, jong[t]])
                check(dbcs_model_decode(table, data, extra_dec) == dec(data, codec),
                      f"euc_kr: make-up {data.hex()}")
    for pos in range(2, 8):
        for b in range(0x100):
            data = bytearray(b"\xa4\xd4\xa4\xa1\xa4\xbf\xa4\xd4")
            data[pos] = b
            data = bytes(data)
            check(dbcs_model_decode(table, data, extra_dec) == dec(data, codec),
                  f"euc_kr: make-up {data.hex()}")
    for n in range(2, 8):
        data = b"\xa4\xd4\xa4\xa1\xa4\xbf\xa4\xd4"[:n]
        check(dbcs_model_decode(table, data, extra_dec) == dec(data, codec), "euc_kr: short")
    return table, ovr, (cho, jung, jong)


# GB18030: GBK-style two-byte table, four-byte BMP ranges, four-byte
# supplementary planes (linear 189000 + cp - #x10000).
def gb_linear(b):
    return (((b[0] - 0x81) * 10 + (b[1] - 0x30)) * 126 + (b[2] - 0x81)) * 10 + (b[3] - 0x30)


def gb_bytes(linear):
    linear, b4 = divmod(linear, 10)
    linear, b3 = divmod(linear, 126)
    b1, b2 = divmod(linear, 10)
    return bytes([b1 + 0x81, b2 + 0x30, b3 + 0x81, b4 + 0x30])


def gb18030():
    codec = "gb18030"
    table = Dbcs(codec, lambda b: dec(b, codec))
    check(not any(0x30 <= t <= 0x39 for t in range(table.trail_min, table.trail_max + 1)
                  for l in range(table.lead_min, table.lead_max + 1) if table.lookup(l, t)),
          "gb18030: two-byte trail in 30-39")
    # BMP four-byte area: linear 0 .. 39419.
    runs = []  # [linear-start, cp-start, length]
    for linear in range(39420):
        text = dec(gb_bytes(linear), codec)
        if text is None:
            continue
        check(len(text) == 1, "gb18030: four-byte length")
        cp = ord(text)
        if runs and runs[-1][0] + runs[-1][2] == linear and runs[-1][1] + runs[-1][2] == cp:
            runs[-1][2] += 1
        else:
            runs.append([linear, cp, 1])
    check(all(a[1] + a[2] <= b[1] for a, b in zip(runs, runs[1:])), "gb18030: runs not sorted by cp")

    def four_byte_decode(linear):
        if linear < 39420:
            for start, cp, length in runs:
                if start <= linear < start + length:
                    return cp + linear - start
            return None
        if 189000 <= linear < 189000 + 0x100000:
            return linear - 189000 + 0x10000
        return None

    def extra_dec(data, i):
        if i + 1 < len(data) and 0x30 <= data[i + 1] <= 0x39:
            if not (0x81 <= data[i] <= 0xFE) or i + 3 >= len(data):
                return False
            if not (0x81 <= data[i + 2] <= 0xFE and 0x30 <= data[i + 3] <= 0x39):
                return False
            cp = four_byte_decode(gb_linear(data[i:i + 4]))
            return False if cp is None else (cp, i + 4)
        return None

    def extra_enc(cp):
        if cp >= 0x10000:
            return gb_bytes(cp - 0x10000 + 189000)
        for start, first, length in runs:
            if first <= cp < first + length:
                return gb_bytes(start + cp - first)
        return None

    python_map = python_encode_map(codec, ALL_CPS)
    # Overrides only against the two-byte inverse + four-byte model.
    model = dict(table.inverse)
    for cp in python_map:
        if cp not in model:
            out = extra_enc(cp)
            if out is not None:
                model[cp] = out
    for cp in list(model):
        pass
    ovr = []
    for cp in sorted(set(model) | set(python_map)):
        if model.get(cp) != python_map.get(cp):
            want = python_map.get(cp)
            ovr.append((cp, pack(want) if want is not None else None))
    inverse = apply_overrides(table.inverse, ovr)
    # Overrides that remove a cp must also stop the four-byte fallback.
    removed = {cp for cp, packed in ovr if packed is None}

    def extra_enc_checked(cp):
        return None if cp in removed else extra_enc(cp)

    verify_dbcs(codec, table, inverse, extra_dec, extra_enc_checked)
    for linear in list(range(0, 39420 + 200)) + list(range(189000 - 50, 189050)) + \
            list(range(189000 + 0x100000 - 50, 189000 + 0x100000 + 50)):
        data = gb_bytes(linear)
        check(dbcs_model_decode(table, data, extra_dec) == dec(data, codec),
              f"gb18030: four-byte {data.hex()}")
    for data in (b"\x81\x30", b"\x81\x30\x81", b"\x81\x30\x20\x30", b"\x81\x30\x81\x20",
                 b"\x30\x30", b"\xff\x30\x81\x30", b"\x81\x30\xff\x30"):
        check(dbcs_model_decode(table, data, extra_dec) == dec(data, codec),
              f"gb18030: {data.hex()}")
    return table, ovr, runs


# ISO-2022-JP (RFC 1468): ASCII, JIS X 0201 Roman, JIS X 0208 (ESC $ @ / ESC $ B).
ESC_ASCII, ESC_ROMAN, ESC_JIS, ESC_JIS_OLD = b"\x1b(B", b"\x1b(J", b"\x1b$B", b"\x1b$@"


def iso2022jp():
    codec = "iso2022_jp"
    jis = Dbcs(codec, lambda b: dec(ESC_JIS + b + ESC_ASCII, codec), range(0x21, 0x7F))
    for lead in range(0x21, 0x7F):
        for trail in range(0x21, 0x7F):
            check(dec(ESC_JIS_OLD + bytes([lead, trail]), codec)
                  == dec(ESC_JIS + bytes([lead, trail]), codec), "iso2022_jp: ESC $ @")
    roman = {}
    jis_map = {}
    for cp in ALL_CPS:
        if cp < 0x80:
            check(enc(chr(cp), codec) == bytes([cp]), "iso2022_jp: ASCII")
            continue
        out = enc(chr(cp), codec)
        if out is None:
            continue
        if out.startswith(ESC_ROMAN):
            check(len(out) == 7 and out.endswith(ESC_ASCII), "iso2022_jp: roman")
            roman[cp] = out[3]
        else:
            check(out.startswith(ESC_JIS) and len(out) == 8 and out.endswith(ESC_ASCII),
                  f"iso2022_jp: U+{cp:04X} -> {out!r}")
            jis_map[cp] = out[3:5]
    ovr = overrides(jis.inverse, jis_map)
    inverse = apply_overrides(jis.inverse, ovr)
    check(not set(roman) & set(inverse), "iso2022_jp: roman overlaps JIS X 0208")

    def model_decode(data):
        """CPython's iso2022 decoder with iso2022_jp's designations (NO_SHIFT,
        USE_JISX0208_EXT): G0 is ASCII, JIS X 0201 Roman or JIS X 0208; G1
        designations are accepted and ignored; ESC not followed by ( ) $ . &
        passes through with the following octets up to a final byte (A-Z, @)."""
        def final(b):
            return 0x41 <= b <= 0x5A or b == 0x40
        out, i, g0, through, n = [], 0, "ascii", False, len(data)
        while i < n:
            c = data[i]
            if through:
                out.append(chr(c))
                i += 1
                through = not final(c)
            elif c == 0x1B:
                if i + 1 >= n:
                    return None
                if data[i + 1] not in b"()$.&":
                    out.append(chr(c))
                    i += 1
                    through = True
                    continue
                esclen, k = 0, 1
                while k < 16:
                    if i + k >= n:
                        return None
                    if final(data[i + k]):
                        esclen = k + 1
                        break
                    if data[i + k] == 0x26 and i + k + 1 < n and data[i + k + 1] == 0x40:
                        k += 2
                    k += 1
                if esclen == 3:
                    b2, b3 = data[i + 1], data[i + 2]
                    if b2 == 0x24:
                        charset, g = ("dbcs", b3), 0
                    elif b2 in (0x28, 0x29):
                        charset, g = ("sbcs", b3), (0 if b2 == 0x28 else 1)
                    else:
                        return None
                elif esclen == 4:
                    if data[i + 1] != 0x24 or data[i + 2] not in (0x28, 0x29):
                        return None
                    charset, g = ("dbcs", data[i + 3]), (0 if data[i + 2] == 0x28 else 1)
                elif esclen == 6:
                    if data[i + 3:i + 6] != b"\x1b$B":
                        return None
                    charset, g = ("dbcs", 0x42), 0
                else:
                    return None
                modes = {("sbcs", 0x42): "ascii", ("sbcs", 0x4A): "roman",
                         ("dbcs", 0x42): "jis", ("dbcs", 0x40): "jis"}
                if charset not in modes:
                    return None
                if g == 0:
                    g0 = modes[charset]
                i += esclen
            elif c >= 0x80:
                return None
            elif c < 0x20 or g0 == "ascii":
                out.append(chr(c))
                i += 1
            elif g0 == "roman":
                out.append({0x5C: "\u00a5", 0x7E: "\u203e"}.get(c, chr(c)))
                i += 1
            else:
                if i + 1 >= n:
                    return None
                cp = jis.lookup(c, data[i + 1])
                if not cp:
                    return None
                out.append(chr(cp))
                i += 2
        return "".join(out)

    def model_encode(text):
        out, mode = bytearray(), "ascii"
        for ch in text:
            cp = ord(ch)
            if cp < 0x80:
                want, code = "ascii", bytes([cp])
            elif cp in inverse:
                want, code = "jis", inverse[cp]
            elif cp in roman:
                want, code = "roman", bytes([roman[cp]])
            else:
                return None
            if want != mode:
                out += {"ascii": ESC_ASCII, "roman": ESC_ROMAN, "jis": ESC_JIS}[want]
                mode = want
            out += code
        if mode != "ascii":
            out += ESC_ASCII
        return bytes(out)

    check(sorted(roman.items()) == [(0xA5, 0x5C), (0x203E, 0x7E)], "iso2022_jp: roman set")
    for prefix in (b"", ESC_ASCII, ESC_ROMAN, ESC_JIS, ESC_JIS_OLD):
        for b in range(0x100):
            data = prefix + bytes([b])
            check(model_decode(data) == dec(data, codec), f"iso2022_jp: {data!r}")
        if prefix in (ESC_JIS, ESC_JIS_OLD):
            for b1 in range(0x100):
                for b2 in range(0x100):
                    data = prefix + bytes([b1, b2])
                    check(model_decode(data) == dec(data, codec), f"iso2022_jp: {data!r}")
    for prefix in (b"", ESC_JIS):
        for b2 in b"()$.&":
            for b3 in range(0x100):
                for b4 in range(0x100):
                    data = prefix + bytes([0x1B, b2, b3, b4])
                    check(model_decode(data) == dec(data, codec), f"iso2022_jp: {data!r}")
    for seq in [b"\x1b", b"\x1b(", b"\x1b$", b"\x1b&@", b"\x1b&@\x1b$B", b"\x1b&@\x1b$@",
                b"\x1b&@\x1b(B", b"\x1b$((B", b"\x1bN", b"\x1bx\xffyZ", b"\x1b(" + b"!" * 20]:
        for tail in (b"", b"ab", b"F|", b"\x80"):
            check(model_decode(seq + tail) == dec(seq + tail, codec), f"iso2022_jp: {seq + tail!r}")
    for cp in ALL_CPS:
        check(model_encode(chr(cp)) == enc(chr(cp), codec), f"iso2022_jp: encode U+{cp:04X}")
    rng = random.Random(2022)
    pool = [chr(c) for c in range(0x20, 0x7F)] + ["\n", "¥", "‾"] + \
           [chr(c) for c in list(inverse)[::37]]
    for _ in range(3000):
        text = "".join(rng.choice(pool) for _ in range(rng.randint(0, 12)))
        check(model_encode(text) == enc(text, codec), f"iso2022_jp: encode {text!r}")
        check(model_decode(enc(text, codec)) == text, f"iso2022_jp: round trip {text!r}")
    return jis, ovr, roman, model_encode


# ---------------------------------------------------------------- writers


def lisp_ints(values, per_line=16, indent="    "):
    lines = []
    for i in range(0, len(values), per_line):
        lines.append(indent + " ".join(str(v) for v in values[i:i + per_line]))
    return "\n".join(lines)


def lisp_overrides(ovr):
    if not ovr:
        return "()"
    items = [f"({cp})" if packed is None else f"({cp} . {packed})" for cp, packed in ovr]
    return "(" + "\n    ".join(" ".join(items[i:i + 6]) for i in range(0, len(items), 6)) + ")"


def write(path, text):
    full = os.path.join(ROOT, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {path} ({len(text.encode('utf-8'))} bytes)")


def table_form(var, table_or_data, ovr, doc, lead=None, trail=None):
    if lead is None:
        data = table_or_data
        head = f"(define-code-table {var}\n  :documentation \"{doc}\""
    else:
        data = table_or_data.data
        head = (f"(define-code-table {var}\n  :documentation \"{doc}\"\n"
                f"  :lead ({lead[0]} {lead[1]}) :trail ({trail[0]} {trail[1]})")
    return (head + f"\n  :overrides {lisp_overrides(ovr)}\n  :data\n   (\n"
            + lisp_ints(data) + "))\n")


