def multibyte_fixture(multi):
    """Round trips (decoded text <-> Python's octets) over a broad sample, plus
    unencodable code points and invalid octet sequences, per codec."""
    rng = random.Random(1980)
    out = [";; Generated by tools/gen-charsets.py: Python's answers for a broad sample.",
           ";; (codec (:round-trip (code points) (octets)) ... (:unencodable cp ...) (:invalid (octets) ...))"]
    for codec, table in multi:
        chars = sorted({cp for cp in table.data if cp})
        if codec == "gb18030":
            chars += rng.sample([cp for cp in BMP_CPS if cp >= 0x80], 3000)
            chars += rng.sample(range(0x10000, 0x110000), 300)
        if codec == "euc_kr":
            chars += rng.sample(range(0xAC00, 0xD7A4), 500)
        if codec == "iso2022_jp":
            chars += [0xA5, 0x203E] * 20 + list(range(0x20, 0x7F))
        sample = [cp for cp in chars if enc(chr(cp), codec) is not None]
        rng.shuffle(sample)
        sample = sample[::5]
        entries = []
        for i in range(0, len(sample), 48):
            cps = sample[i:i + 48]
            if codec == "iso2022_jp":
                cps = cps + [0x0A] + [ord(c) for c in "ASCII"]
            octets = enc("".join(map(chr, cps)), codec)
            check(dec(octets, codec) == "".join(map(chr, cps)), f"{codec}: fixture round trip")
            entries.append(f"(:round-trip ({' '.join(map(str, cps))})\n  ({' '.join(map(str, octets))}))")
        unencodable = [cp for cp in rng.sample(ALL_CPS, 4000) if enc(chr(cp), codec) is None][:40]
        entries.append(f"(:unencodable {' '.join(map(str, unencodable))})")
        invalid = []
        for _ in range(4000):
            data = bytes(rng.randrange(256) for _ in range(rng.randint(1, 4)))
            if codec == "iso2022_jp":
                data = rng.choice([b"", ESC_JIS, ESC_ROMAN, b"\x1b"]) + data
            if dec(data, codec) is None:
                invalid.append(data)
            if len(invalid) >= 60:
                break
        entries.append("(:invalid " + " ".join(f"({' '.join(map(str, d))})" for d in invalid) + ")")
        out.append(f"(\"{codec}\"\n " + "\n ".join(entries) + ")")
    return "\n".join(out) + "\n"


